    ["DUNGEON DROP"] = "DUNGEON",
    ["HONOR / REPUTATION"] = "HONOR / REP",
}

GearAcquisition.catalogs = { ERA = era, TBC = tbc }
GearAcquisition.counts = { ERA = 652, TBC = 664 }

function GearAcquisition:Get(itemID, clientKey)
    local catalog = self.catalogs[clientKey or "ERA"] or self.catalogs.ERA
    return itemID and catalog[itemID] or nil
end

function GearAcquisition:Format(itemData, clientKey)
    local metadata = itemData and self:Get(itemData.id,clientKey)
    if not metadata then return nil end
    local source = sourceLabels[metadata.source] or metadata.source
    if clientKey == "ERA" and itemData.requiresNaxxEnchant and metadata.source == "WORLD DROP" then source = "WORLD" end
    local text = (bindingLabels[metadata.binding] or metadata.binding)
        .. " |cff627089·|r " .. source
    if clientKey == "ERA" and itemData.requiresNaxxEnchant then
        text = text .. " |cff627089·|r |cfff2ad4c+ NAXX|r"
    end
    return text
end

